create table if not exists public.family_backups (
  id bigint generated by default as identity primary key,
  family_id uuid not null references public.families(id) on delete cascade,
  revision bigint not null,
  data jsonb not null,
  reason text not null default 'auto',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists family_backups_family_created_idx
  on public.family_backups (family_id, created_at desc);

alter table public.family_backups enable row level security;

drop policy if exists "family members can read backups" on public.family_backups;
create policy "family members can read backups"
on public.family_backups for select
to authenticated
using (
  exists (
    select 1 from public.family_members fm
    where fm.family_id = family_backups.family_id
      and fm.user_id = auth.uid()
  )
);

