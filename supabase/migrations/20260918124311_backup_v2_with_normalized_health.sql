create or replace function private.family_data_without_health(p_data jsonb)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select jsonb_set(
    coalesce(p_data, '{}'::jsonb),
    '{deadlines}',
    coalesce((
      select jsonb_agg(e.value order by e.ord)
      from jsonb_array_elements(coalesce(p_data->'deadlines', '[]'::jsonb)) with ordinality as e(value, ord)
      where coalesce(e.value->>'kind', 'general') not in ('medicine','therapy','visit','health-record')
    ), '[]'::jsonb),
    true
  )
$$;

create or replace function private.health_backup_items(p_family_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
with items as (
  select
    1 as grp,
    hm.legacy_id as sort_id,
    jsonb_strip_nulls(jsonb_build_object(
      'id', hm.legacy_id,
      'title', hm.title,
      'date', hm.legacy_date,
      'userId', 0,
      'done', hm.archived,
      'kind', 'medicine',
      'activeIngredient', hm.active_ingredient,
      'purpose', hm.purpose,
      'notes', hm.notes,
      'defaultPackageSize', hm.default_package_size,
      'packages', coalesce((
        select jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
          'id', hp.legacy_id,
          'expiryDate', hp.expiry_date,
          'quantity', hp.quantity,
          'packageSize', hp.package_size,
          'lot', hp.lot,
          'addedAt', hp.added_at
        )) order by hp.legacy_id)
        from public.health_medicine_packages hp
        where hp.family_id = hm.family_id and hp.medicine_id = hm.id
      ), '[]'::jsonb)
    )) as item
  from public.health_medicines hm
  where hm.family_id = p_family_id

  union all

  select
    2,
    ht.legacy_id,
    jsonb_strip_nulls(jsonb_build_object(
      'id', ht.legacy_id,
      'title', ht.title,
      'date', coalesce(ht.legacy_date, ht.end_date, ht.start_date),
      'userId', fp.legacy_user_id,
      'done', ht.archived,
      'kind', 'therapy',
      'prescriber', ht.prescriber,
      'purpose', ht.purpose,
      'notes', ht.notes,
      'therapyStartDate', ht.start_date,
      'therapyEndDate', ht.end_date,
      'therapyMedicines', coalesce((
        select jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
          'id', htm.legacy_id,
          'medicineId', hm2.legacy_id,
          'tabletsPerDose', htm.tablets_per_dose,
          'dosesPerDay', htm.doses_per_day,
          'usage', htm.usage
        )) order by htm.legacy_id)
        from public.health_therapy_medicines htm
        join public.health_medicines hm2 on hm2.id = htm.medicine_id
        where htm.family_id = ht.family_id and htm.therapy_id = ht.id
      ), '[]'::jsonb),
      'attachments', coalesce((
        select jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
          'id', ha.id,
          'name', ha.file_name,
          'path', ha.storage_path,
          'mimeType', ha.mime_type,
          'size', ha.file_size,
          'createdAt', ha.created_at
        )) order by ha.created_at)
        from public.health_attachments ha
        where ha.family_id = ht.family_id and ha.therapy_id = ht.id
      ), '[]'::jsonb)
    ))
  from public.health_therapies ht
  join public.family_people fp on fp.id = ht.person_id
  where ht.family_id = p_family_id

  union all

  select
    3,
    hv.legacy_id,
    jsonb_strip_nulls(jsonb_build_object(
      'id', hv.legacy_id,
      'title', hv.title,
      'date', hv.visit_date,
      'time', case when hv.visit_time is null then null else to_char(hv.visit_time, 'HH24:MI') end,
      'userId', fp.legacy_user_id,
      'done', hv.status <> 'scheduled',
      'kind', 'visit',
      'healthStatus', hv.status,
      'specialty', hv.specialty,
      'doctor', hv.doctor,
      'facility', hv.facility,
      'purpose', hv.purpose,
      'outcome', hv.outcome,
      'notes', hv.notes,
      'nextVisitDate', hv.next_visit_date,
      'followUpEvery', hv.follow_up_every,
      'followUpUnit', hv.follow_up_unit,
      'followUpVisitId', hv.follow_up_visit_legacy_id,
      'followUpSourceId', hv.follow_up_source_legacy_id,
      'autoGenerated', hv.auto_generated,
      'calendarEventId', hv.calendar_event_id,
      'bookingReminderEvery', hv.booking_reminder_every,
      'bookingReminderUnit', hv.booking_reminder_unit,
      'bookingReminderEventId', hv.booking_reminder_event_id,
      'attachments', coalesce((
        select jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
          'id', ha.id,
          'name', ha.file_name,
          'path', ha.storage_path,
          'mimeType', ha.mime_type,
          'size', ha.file_size,
          'createdAt', ha.created_at
        )) order by ha.created_at)
        from public.health_attachments ha
        where ha.family_id = hv.family_id and ha.visit_id = hv.id
      ), '[]'::jsonb)
    ))
  from public.health_visits hv
  join public.family_people fp on fp.id = hv.person_id
  where hv.family_id = p_family_id

  union all

  select
    4,
    hr.legacy_id,
    jsonb_strip_nulls(jsonb_build_object(
      'id', hr.legacy_id,
      'title', hr.title,
      'date', hr.record_date,
      'userId', fp.legacy_user_id,
      'done', false,
      'kind', 'health-record',
      'healthRecordKind', hr.record_kind,
      'provider', hr.provider,
      'result', hr.result,
      'notes', hr.notes,
      'attachments', coalesce((
        select jsonb_agg(jsonb_strip_nulls(jsonb_build_object(
          'id', ha.id,
          'name', ha.file_name,
          'path', ha.storage_path,
          'mimeType', ha.mime_type,
          'size', ha.file_size,
          'createdAt', ha.created_at
        )) order by ha.created_at)
        from public.health_attachments ha
        where ha.family_id = hr.family_id and ha.record_id = hr.id
      ), '[]'::jsonb)
    ))
  from public.health_records hr
  join public.family_people fp on fp.id = hr.person_id
  where hr.family_id = p_family_id
)
select coalesce(jsonb_agg(item order by grp, sort_id), '[]'::jsonb)
from items
$$;

